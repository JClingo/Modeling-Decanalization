"""Regenerate movement-*.dat (agent positions) and movement-stats.tex (patches, summaries) for figures/movement.tex.

Re-runs the paired example trial shown in trajectory.tex: the first evaluation seed (5000+) in which
the undisturbed stable-trained HRL policy (training seed 0) is trapped in phase 3 and the decanalized
one (d = 1, boost 1) is not. Needs the simulation repository (default: ../../decanalization next to
this repository; override with DECANALIZATION_MODEL=/path/to/decanalization/model) and numpy.

Run from any directory: python3 figures/make-movement-data.py
Then compile movement.tex from figures/ with pdflatex.
"""
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MODEL = Path(os.environ.get("DECANALIZATION_MODEL", HERE.parents[1] / "decanalization" / "model"))
sys.path.insert(0, str(MODEL))
import numpy as np  # noqa: E402
from mapagent import MapParams  # noqa: E402
from policy_agent import OptionTrial  # noqa: E402
from settings import WORLD  # noqa: E402
from world import phase_dose  # noqa: E402

local = MODEL / "runs" / "policy_HRL_stable.npz"
weights = list(np.load(local if local.exists() else MODEL.parent / "results" / "policies" / "policy_HRL_stable.npz").values())
BOUNDS = (0.0, 300.0, 400.0, 700.0)


class Recorded(OptionTrial):
    """Keeps a snapshot of patch fertility at each phase boundary."""

    def step(self, action=None):
        before = self.t
        super().step(action)
        for b in BOUNDS[1:]:
            if before < b <= self.t + 1e-9:
                self.snap[b] = [self.fertility(k) for k in range(len(self.q))]


def run(seed, arm):
    p = MapParams(**WORLD)
    if arm == "CCC":
        trial = Recorded(p, seed, phase_dose(p, "CCC"), "HRL", weights)
    else:
        trial = Recorded(p, seed, phase_dose(p, "DOSE", 1.0, 100.0), "HRL", weights, temp_boost=1.0)
    trial.snap = {}
    return trial.run()


for seed in range(5000, 5064):
    ccc, cdr = run(seed, "CCC"), run(seed, "CDR")
    hu = [s[3] for s in ccc.log["samples"]]
    hd = [s[3] for s in cdr.log["samples"]]
    if min(hu[800:]) <= -100 and min(hd[800:]) > -100:
        break
else:
    raise SystemExit("no example trial found")

grid = ccc.p.grid
stats = []
for name, trial in (("ccc", ccc), ("cdr", cdr)):
    # Positions every 0.5 s; a nan row breaks the line where the agent wraps around the torus.
    lines = ["t x y h"]
    prev = None
    for t, x, y, h, *_ in trial.log["samples"]:
        if prev and (abs(x - prev[0]) > grid / 2 or abs(y - prev[1]) > grid / 2):
            lines.append("nan nan nan nan")
        lines.append(f"{t:.1f} {x:.2f} {y:.2f} {h:.2f}")
        prev = (x, y)
    (HERE / f"movement-{name}.dat").write_text("\n".join(lines) + "\n")

    # Patches as TikZ commands: familiar patches fade with fertility at the end of each phase;
    # new patches are outlined dashed before they appear at 300 s, solid afterwards.
    corners = [np.argwhere(trial.patch_of == k).min(0) for k in range(len(trial.q))]
    for phase, (lo, hi) in enumerate(zip(BOUNDS, BOUNDS[1:])):
        hs = [s[3] for s in trial.log["samples"] if lo < round(s[0], 3) <= hi]
        new = sum(1 for hv in trial.log["harvests"] if lo <= round(hv[0], 3) < hi and hv[1] in trial.rich)
        old = sum(1 for hv in trial.log["harvests"] if lo <= round(hv[0], 3) < hi and hv[1] not in trial.rich)
        print(f"{name} {lo:.0f}-{hi:.0f}s: mean|h| {np.mean(np.abs(hs)):.1f}  min h {min(hs):.1f}  "
              f"harvests familiar {old}  new {new}")
        tag = name + "ABC"[phase]
        stats += [f"\\def\\mae{tag}{{{np.mean(np.abs(hs)):.1f}}}", f"\\def\\old{tag}{{{old}}}",
                  f"\\def\\new{tag}{{{new}}}", f"\\def\\minh{tag}{{{min(hs):.0f}}}"]
        draws = []
        for k, (x0, y0) in enumerate(corners):
            box = f"(axis cs:{x0},{y0}) rectangle (axis cs:{x0 + 3},{y0 + 3});"
            if k not in trial.rich:
                draws.append(f"\\fill[food,fill opacity={max(0.12, trial.snap[hi][k]):.2f}] {box}")
            elif phase == 0:
                draws.append(f"\\filldraw[fill=newp!15,draw=newp,dashed,line width=1pt] "
                             f"(axis cs:{x0 - 0.6},{y0 - 0.6}) rectangle (axis cs:{x0 + 3.6},{y0 + 3.6});")
            else:
                draws.append(f"\\filldraw[fill=newp,draw=newp!60!black,line width=0.7pt] {box}")
        stats.append(f"\\def\\patches{tag}{{" + "".join(draws) + "}")
        inside = [s for s in trial.log["samples"] if lo < round(s[0], 3) <= hi]
        stats += [f"\\def\\start{tag}{{{inside[0][1]:.2f},{inside[0][2]:.2f}}}",
                  f"\\def\\stop{tag}{{{inside[-1][1]:.2f},{inside[-1][2]:.2f}}}"]
(HERE / "movement-stats.tex").write_text(f"% Generated by make-movement-data.py (evaluation seed {seed})\n" + "\n".join(stats) + "\n")
print("example trial seed", seed)
